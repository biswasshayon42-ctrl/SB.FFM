export function getRankTier(rp: number): { name: string; color: string } {
  if (rp >= 3200) return { name: 'Grandmaster', color: '#f43f5e' };
  if (rp >= 2400) return { name: 'Heroic', color: '#f59e0b' };
  if (rp >= 1800) return { name: 'Diamond', color: '#38bdf8' };
  if (rp >= 1300) return { name: 'Platinum', color: '#22d3ee' };
  if (rp >= 800) return { name: 'Gold', color: '#fbbf24' };
  return { name: 'Bronze', color: '#94a3b8' };
}
